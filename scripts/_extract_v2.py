def extract_xlsx(path):
    wb = openpyxl.load_workbook(path, data_only=True)
    subs = []
    current = None
    for sn in wb.sheetnames:
        if '汇总' in sn: continue
        ws = wb[sn]
        for r in range(1, ws.max_row + 1):
            v1 = ws.cell(r, 1).value
            v2 = ws.cell(r, 2).value
            v3 = ws.cell(r, 3).value
            if v1 and isinstance(v1, str):
                if (re.match(r'^[一二三四五六七八九十]+、', v1) and len(v1) < 35) and (v2 is None or v2 == ''):
                    current = re.sub(r'^[一二三四五六七八九十]+、', '', v1).strip()
                    continue
                if (re.match(r'^\d+\.', v1) and len(v1) < 60) and (v2 is None or v2 == ''):
                    current = re.sub(r'^\d+\.\s*', '', v1).strip()
                    continue
            brand = None
            if v3 and isinstance(v3, str) and v3.strip() and v3 not in ('品牌', '品类', '序号', '规格', '系列', '品牌/书名', '规格/内容'):
                if current:
                    brand = v3.strip()
            elif v1 and isinstance(v1, str) and v1.strip() and v1 not in ('品牌', '品类', '序号', '规格', '系列', '品牌/书名', '规格/内容', '微唯宝供货价', '京东供货价', '京东零售价', '微唯宝价', '京东价', '备注', '备注/报价说明'):
                if v2 and isinstance(v2, str) and v2 not in ('品牌', '品类', '序号', '规格', '系列'):
                    if current:
                        brand = v1.strip()
            if brand and current:
                subs.append((current, brand))
    return subs

all_data = {}
for f, cat_name in FILE_TO_CAT_NAME.items():
    fp = os.path.join(p, f)
    if not os.path.exists(fp):
        print(f'MISSING: {f}')
        continue
    subs = extract_xlsx(fp)
    all_data[cat_name] = subs
    print(f'{f}: {len(subs)} SKU')

final = {}
for cat, subs in all_data.items():
    by_sub = {}
    for sub, brand in subs:
        by_sub.setdefault(sub, []).append(brand)
    weight_cat = WEIGHT.get(cat, {})
    ordered = []
    for sub, brands in by_sub.items():
        order = None
        for wkey, wlist in weight_cat.items():
            if wkey in sub or sub in wkey:
                order = wlist
                break
        if order:
            seen = set()
            ob = []
            for w in order:
                for b in brands:
                    if b == w and b not in seen:
                        ob.append(b); seen.add(b); break
            for b in brands:
                if b not in seen:
                    ob.append(b); seen.add(b)
            brands = ob
        ordered.append([sub, brands])
    final[cat] = ordered

out = os.path.join(p, '_data_v2.json')
with open(out, 'w', encoding='utf-8') as f:
    json.dump(final, f, ensure_ascii=False, indent=2)

total_brands = set()
for cat, subs in final.items():
    for sub, brands in subs:
        for b in brands:
            total_brands.add(b)
print(f'\n唯一品牌: {len(total_brands)}')
print(f'小类总数: {sum(len(s) for s in final.values())}')
print(f'saved to {out}')
